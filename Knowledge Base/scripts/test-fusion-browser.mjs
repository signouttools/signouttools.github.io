// Exercise production search/filter/link functions against the generated static corpus.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const fields=Object.fromEntries(['search','category','tumor'].map(id=>[id,{value:''}]));
const location={pathname:'/Knowledge%20Base/',href:'http://127.0.0.1:8766/Knowledge%20Base/'};
let replacedURL;
const context=vm.createContext({document:{getElementById:id=>fields[id]},location,URL,URLSearchParams,history:{replaceState:(_a,_b,url)=>{replacedURL=url;}}});
const code=fs.readFileSync(path.join(root,'app.js'),'utf8').replace(/\ninit\(\);\s*$/,'\n');
vm.runInContext(code,context);
context.records=read('data/fusion-browser.json').records;
context.genes=read('data/gene-index.json');
context.diseases=[...read('data/diseases.json'),...read('data/fusion-diseases.json')];
vm.runInContext(`state.fusions=records; state.genes=genes; state.diseaseMap=new Map(diseases.map(d=>[d.id,d])); state.fusionSearchMap=new Map(records.map(f=>[f.id,fusionNormalize([f.label,...f.aliases,...f.partners.map(p=>p.symbol),...f.tumor_contexts,...f.sections.map(s=>s.text)].join(' '))]));`,context);
const result=()=>JSON.parse(vm.runInContext('JSON.stringify(matchingFusions().map(f=>f.label))',context));
const query=q=>{fields.search.value=q;return result();};
assert(query('EML4::ALK').includes('EML4::ALK'));
assert(query('ALK EML4').includes('EML4::ALK'));
assert(query('ALK-EML4').includes('EML4::ALK'));
assert(query('MLL AF6').includes('KMT2A::AFDN'),'legacy fusion alias');
assert(query('MLL ABI1').includes('KMT2A::ABI1'),'new KMT2A legacy alias');
assert(query('FAM118B YAP1').includes('YAP1::SIRAL1'),'renamed partner remains searchable');
assert(query('C11orf95 MAML2').includes('ZFTA::MAML2'),'source-era ZFTA symbol remains searchable');
assert(query('NTRK2 AFAP1').includes('AFAP1::NTRK2'),'new partner reverse search');
assert.equal(vm.runInContext(`fusionEvidenceLabel(records.find(f=>f.label==='KMT2A::ABI1'))`,context),'Cohort observation · Draft');
assert.equal(vm.runInContext(`fusionEvidenceLabel(records.find(f=>f.label==='EML4::ALK'))`,context),'Primary results checked · Draft');
assert(query('NTRK2 ETV6').includes('ETV6::NTRK2'),'restored fusion must be searchable');
assert.equal(query('does-not-exist-unique-token').length,0);
fields.search.value='';fields.category.value='hematologic';
assert(!result().includes('EML4::ALK'),'lung fusion must not enter heme filter');
assert(result().includes('KMT2A::ABI1'),'new leukemia observation has hematologic category');
assert(!result().includes('AFAP1::NTRK2'),'brain cohort observation must not enter heme filter');
fields.category.value='';fields.tumor.value='aml';
assert(result().includes('RUNX1::RUNX1T1'),'AML parent should include audited AML subtype');
assert(result().includes('ETV6::NTRK2'),'restored ETV6::NTRK2 must use its audited AML scope');
assert(!result().includes('EML4::ALK'),'lung fusion must not enter AML filter');
assert(result().includes('KMT2A::ABI1'),'new pediatric AML observation inherits AML filter');
assert(!result().includes('AFAP1::NTRK2'),'brain cohort observation must not enter AML filter');
fields.tumor.value='';fields.search.value='';
context.alkID=vm.runInContext(`state.genes.find(g=>g.symbol==='ALK').id`,context);
assert(vm.runInContext('fusionsForGene({id:alkID}).some(f=>f.label==="EML4::ALK")',context));
vm.runInContext(`state.mode='fusions';state.selected='fusion-eml4-alk';updateURL();`,context);
assert(replacedURL.includes('mode=fusions')&&replacedURL.includes('fusion=fusion-eml4-alk'));
assert(!replacedURL.includes('gene='));
vm.runInContext(`state.mode='genes';state.selected=alkID;state.tab='fusions';updateURL();`,context);
assert(replacedURL.includes('view=fusions')&&replacedURL.includes('gene=HGNC'));
assert(!replacedURL.includes('mode=fusions'));
console.log('Passed fusion partner-order/alias search, empty results, disease/category isolation, gene links and deep-link state.');
